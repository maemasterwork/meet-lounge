// Generates supabase/seed.sql from the app catalog + Persian/English copy, so DB and UI never drift.
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
const out = await build({ entryPoints: ['src/data/catalog.ts'], bundle: true, write: false, format: 'esm', platform: 'node' })
const mod = await import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'))
const fa = JSON.parse(readFileSync('src/i18n/fa.json', 'utf8')), en = JSON.parse(readFileSync('src/i18n/en.json', 'utf8'))
const q = (s) => "'" + String(s ?? '').replace(/'/g, "''") + "'"
const items = mod.initialMenu()
if (!items) throw new Error('exports: ' + Object.keys(mod))
const rows = items.map((m, i) => {
  const n = (d) => d[`item.${m.id}.name`] ?? d[`goods.${m.id}.name`] ?? m.id
  const ds = (d) => d[`item.${m.id}.desc`] ?? ''
  return `  (${q(m.id)}, ${q(m.cat)}, ${q(n(fa))}, ${q(n(en))}, ${q(ds(fa))}, ${q(ds(en))}, ${m.price}, ${q(JSON.stringify(m.sizes))}::jsonb, ${m.milk}, ${m.rewardEligible}, ${q(`{${m.tags.join(',')}}`)}, ${q(m.art)}, ${i})`
})
const sql = `-- Meet Lounge seed data. Generated by scripts/gen-seed.mjs; safe to re-run.
insert into public.settings (id) values (1) on conflict (id) do nothing;

insert into public.menu_items (id, category, name_fa, name_en, description_fa, description_en, base_price, sizes, milk_options, reward_eligible, tags, art, sort)
values
${rows.join(',\n')}
on conflict (id) do update set category = excluded.category, name_fa = excluded.name_fa, name_en = excluded.name_en,
  description_fa = excluded.description_fa, description_en = excluded.description_en, base_price = excluded.base_price,
  sizes = excluded.sizes, milk_options = excluded.milk_options, reward_eligible = excluded.reward_eligible,
  tags = excluded.tags, art = excluded.art, sort = excluded.sort;

-- A first playful offer so the notification has something to show.
insert into public.offers (title_fa, title_en, body_fa, body_en, item_id, discount_pct, audience)
select 'لاتهٔ امروز دلش می‌خواد ببینتت ☕', 'Today''s latte misses you ☕', 'لاته با ۱۵٪ تخفیف تا آخر امروز.', 'Latte, 15% off until closing today.', 'latte', 15, 'all'
where not exists (select 1 from public.offers);
`
writeFileSync('supabase/seed.sql', sql)
console.log('items', items.length)
